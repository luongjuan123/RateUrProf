def build_final_roster() -> List[Dict[str, Any]]:
    """Builds clean, normalized, and validated professor records."""
    uni_id = "my-thuat-cong-nghiep"
    uni_name = "Trường Đại học Mỹ thuật Công nghiệp"
    uni_short = "MTCN"

    # Handle duplicate names by adding year of birth to the canonical ID
    name_counts: Dict[str, int] = {}
    for item in RAW_MTCN_ROSTER:
        n = item["name"]
        name_counts[n] = name_counts.get(n, 0) + 1

    roster: List[Dict[str, Any]] = []

    for item in RAW_MTCN_ROSTER:
        name = item["name"]
        yob = item["yob"]
        gender = item["gender"]
        faculty = item["faculty"]
        department = item["department"]
        specialty = item["specialty"]
        position = item["position"]
        rank = item["academic_rank"]
        degree = item["degree"]
        title = item["title"]

        # Validate name
        is_valid, _ = RecordValidator.is_valid_human_name(name)
        if not is_valid:
            print(f"[Warning] Invalid name skipped: {name}")
            continue

        # Generate unique canonical ID
        if name_counts[name] > 1:
            slug = Normalizer.normalize_name_for_matching(name).replace(" ", "-")
            prof_id = f"prof-{uni_id}-{slug}-{yob}"
        else:
            prof_id = Normalizer.make_canonical_professor_id(uni_id, name)

        # Build informative biographical summary
        gender_word = "Thầy" if gender == "Nam" else "Cô"
        bio_parts = [
            f"{title} {name} (sinh năm {yob}) là giảng viên cơ hữu thuộc {faculty}, {department} tại {uni_name}."
        ]
        if position and position != "Giảng viên":
            bio_parts.append(f"Hiện giữ chức vụ: {position}.")
        bio_parts.append(f"Chuyên ngành giảng dạy và nghiên cứu chuyên sâu: {specialty}.")
        if item.get("email"):
            bio_parts.append(f"Email công tác: {item['email']}.")
        bio_parts.append(
            "Hồ sơ được đối soát và chứng thực theo Báo cáo Ba Công khai (Biểu mẫu 20) của Bộ Giáo dục & Đào tạo."
        )
        bio = " ".join(bio_parts)

        # Neutral initial avatar fallback
        name_parts = name.strip().split()
        initials = "".join([p[0].upper() for p in name_parts[-2:]]) if len(name_parts) >= 2 else name[:2].upper()
        svg_avatar = (
            f"data:image/svg+xml;utf8,<svg xmlns='http://www.w3.org/2000/svg' width='120' height='120' "
            f"viewBox='0 0 120 120'><rect width='120' height='120' fill='%236366f1'/>"
            f"<text x='50%25' y='55%25' dominant-baseline='middle' text-anchor='middle' "
            f"fill='%23ffffff' font-size='42' font-family='sans-serif' font-weight='bold'>{initials}</text></svg>"
        )

        sources = [BIEU_20_URL, OFFICIAL_PORTAL]
        if item.get("email") or "Hiệu trưởng" in (position or ""):
            sources.append(BGH_URL)

        record = {
            "id": prof_id,
            "name": name,
            "university_id": uni_id,
            "university_name": uni_name,
            "university_short_name": uni_short,
            "faculty": faculty,
            "department": department,
            "title": title,
            "academic_title": degree,
            "academic_rank": rank,
            "position": position,
            "degree": degree,
            "avatar": svg_avatar,
            "bio": bio,
            "verification_status": "verified",
            "confidence_score": 1.0,
            "source_urls": sources,
            "source_type": "official_ba_cong_khai_disclosure",
        }
        roster.append(record)

    return roster


